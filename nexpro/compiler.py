"""Generate standalone Python from a NexPro syntax tree."""

from nexpro.ast import Assign, Binary, Number, Say, String, Variable


def _expression(node, lines):
    if isinstance(node, (String, Number)):
        # Python supports infinity through float(), but has no infinity literal.
        if isinstance(node, Number) and node.value == float("inf"):
            return "float('inf')"
        return repr(node.value)
    if isinstance(node, Variable):
        value = f"_get({node.name!r})"
    elif isinstance(node, Binary) and node.operator in {"+", "-", "*", "/"}:
        left = _expression(node.left, lines)
        right = _expression(node.right, lines)
        value = f"{left} {node.operator} {right}"
    else:
        raise TypeError(f"Unsupported expression {type(node).__name__}")

    # Separate operations avoid Python's nesting limit for long source expressions.
    temporary = f"_value_{len(lines)}"
    lines.append(f"        {temporary} = {value}")
    return temporary


def compile_program(program):
    """Return Python source for a parsed NexPro program."""
    lines = [
        "# Generated by NexPro",
        "import sys",
        "",
        "",
        "_variables = {}",
        "",
        "",
        "def _get(name):",
        "    if name not in _variables:",
        "        raise ValueError(f\"Undefined variable '{name}'\")",
        "    return _variables[name]",
        "",
        "",
        "if __name__ == '__main__':",
        "    try:",
    ]
    for statement in program.statements:
        if isinstance(statement, Assign):
            value = _expression(statement.value, lines)
            lines.append(f"        _variables[{statement.variable.name!r}] = {value}")
        elif isinstance(statement, Say):
            value = _expression(statement.expression, lines)
            lines.append(f"        print({value})")
        else:
            raise TypeError(f"Unsupported statement {type(statement).__name__}")

    if not program.statements:
        lines.append("        pass")

    lines.extend([
        "    except (ArithmeticError, TypeError, ValueError) as error:",
        "        print(f'NexPro Runtime Error: {error}', file=sys.stderr)",
        "        sys.exit(1)",
    ])
    return "\n".join(lines) + "\n"
